#!/usr/bin/env python3
"""
Pump calibration utility.

Calibrates each peristaltic pump's ``steps_per_ml`` by running it at a known
commanded speed for a known duration and weighing the dispensed liquid on a
serial scale, then writes a JSON config that can be loaded by ``src/config.py``.

How it works
------------
Pumps are driven through an instance of the ``Bioreactor`` class (only the pump
being calibrated is enabled), exactly like ``hardware_testing/od_gui.py`` drives
the LED/OD hardware. Mass is read by a separate ``ScaleReader`` that talks to the
scale over serial. For each trial the script:

    1. reads a stable starting mass,
    2. runs the pump at ``speed`` ml/s for ``duration`` s (via ``change_pump``),
    3. stops the pump and waits ``settle`` s,
    4. reads a stable ending mass.

The Tic velocity that ``change_pump`` issues is ``8 * int(speed * steps_per_ml / 8)``
(see ``src/io.py``). Because that same velocity defines the flow rate, the true
calibration is::

    steps_per_ml = (commanded_velocity * run_seconds) / dispensed_ml

independent of whatever ``steps_per_ml`` was in the config during the run.
Dispensed volume is ``dispensed_mass_g / density_g_per_ml``.

The JSON records the Tic settings used during calibration (step_mode,
current_limit, direction, serial), the fitted ``steps_per_ml``, and the raw
trial data, so a calibration is always traceable to the hardware settings it
was measured under.

Loading the result in src/config.py
-----------------------------------
Add this near the bottom of ``src/config.py`` (after the ``PUMPS`` dict is
defined; the JSON lives next to it in ``src/``)::

    # --- pump calibration (generated by hardware_testing/pump_calibration.py) ---
    import json, pathlib
    _cal_path = pathlib.Path(__file__).with_name('pump_calibration.json')
    if _cal_path.exists():
        _cal = json.loads(_cal_path.read_text())
        for _name, _entry in _cal.get('pumps', {}).items():
            if _name in Config.PUMPS:
                Config.PUMPS[_name]['steps_per_ml'] = _entry['steps_per_ml']

(Each entry under ``"pumps"`` is also a complete ``PUMPS`` entry on its own, so
you can copy a whole block in by hand instead if you prefer.)

Usage
-----
    # Calibrate every pump in Config.PUMPS, 3 trials each at 2.0 ml/s for 30 s:
    python hardware_testing/pump_calibration.py

    # Calibrate just the inflow pump, two speeds, longer runs:
    python hardware_testing/pump_calibration.py --pumps inflow \
        --speeds 1.0,2.0 --duration 45 --replicates 2 --port /dev/ttyUSB0

Requires ``pyserial`` (``pip install pyserial``).
"""

